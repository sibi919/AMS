#!/usr/bin/env bash
# Creates .env with freshly generated random secrets for this machine.
#
#   bash docker/scripts/init-env.sh               # create if missing
#   bash docker/scripts/init-env.sh --port 8100   # use a different app port
#
# Nothing here is hardcoded: every password and key is random and stays on this
# machine. .env is git-ignored and is NOT included in the delivered ZIP.
#
# Re-running with an existing .env changes nothing (use --force to regenerate,
# which invalidates existing sessions but not your data).
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$root"

port=8000
mail_port=8025
force=0
while [ $# -gt 0 ]; do
  case "$1" in
    --port) port="$2"; shift 2 ;;
    --mail-port) mail_port="$2"; shift 2 ;;
    --force) force=1; shift ;;
    *) echo "Unknown option: $1"; exit 1 ;;
  esac
done

if [[ -f .env && $force -eq 0 ]]; then
  echo ".env already exists — keeping it (use --force to regenerate)."
  exit 0
fi

command -v openssl >/dev/null || { echo "openssl is required."; exit 1; }

b64url() { openssl base64 -A | tr '+/' '-_' | tr -d '='; }

mint_jwt() {
  local role="$1" secret="$2" iat exp header payload signing_input signature
  iat=$(date +%s)
  exp=$((iat + 60 * 60 * 24 * 365 * 5))
  header=$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)
  payload=$(printf '{"role":"%s","iss":"joab-local","iat":%s,"exp":%s}' "$role" "$iat" "$exp" | b64url)
  signing_input="${header}.${payload}"
  signature=$(printf '%s' "$signing_input" \
    | openssl dgst -sha256 -hmac "$secret" -binary | b64url)
  printf '%s.%s' "$signing_input" "$signature"
}

postgres_password=$(openssl rand -hex 24)
jwt_secret=$(openssl rand -hex 32)
anon_key=$(mint_jwt anon "$jwt_secret")
service_role_key=$(mint_jwt service_role "$jwt_secret")
publishable_key="sb_publishable_$(openssl rand -hex 16)"
public_url="http://localhost:${port}"

umask 077
cat > .env <<EOF
# Generated by docker/scripts/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Local secrets for this machine only. Never commit this file or send it to anyone.
# Delete it and re-run the script to rotate every value.

# ---- Where the application is served -------------------------------------
# Change all three together if port ${port} is already taken on your machine.
APP_PORT=${port}
PUBLIC_URL=${public_url}
VITE_SUPABASE_URL=${public_url}

# Mailpit web interface (password-recovery emails)
MAIL_UI_PORT=${mail_port}

# Set to frontend-prod:8080 when running the optional built-site profile.
FRONTEND_UPSTREAM=frontend:5173

# ---- Keys ----------------------------------------------------------------
# Browser-safe key. This one is meant to appear in the JavaScript bundle.
VITE_SUPABASE_PUBLISHABLE_KEY=${publishable_key}

# Internal only. Never put these in a VITE_ variable or in frontend code.
POSTGRES_PASSWORD=${postgres_password}
JWT_SECRET=${jwt_secret}
JWT_EXPIRY=3600
ANON_KEY=${anon_key}
SERVICE_ROLE_KEY=${service_role_key}
EOF
chmod 600 .env

echo "Created .env"
echo "  application URL : ${public_url}"
echo "  recovery emails : http://localhost:${mail_port}"
echo "  secrets         : random, stored only in .env (permissions 600)"
